import {
  ArrowDownToLine,
  ArrowUpFromLine,
  Database,
  Info,
  Layers,
  Percent,
} from 'lucide-react'
import { useTranslation } from 'react-i18next'

import { Button } from '@/components/ui/button'
import {
  Tooltip,
  TooltipContent,
  TooltipTrigger,
} from '@/components/ui/tooltip'
import { toIntlLocale } from '@/i18n/languages'
import { formatCompactNumber, formatNumber } from '@/lib/format'
import { cn } from '@/lib/utils'

import type { UsageMetrics, UsageSeriesPoint } from '../../usage-types'
import { StatCard } from '../ui/stat-card'

interface UsageSummaryProps {
  summary?: UsageMetrics
  series?: UsageSeriesPoint[]
  loading: boolean
  compact: boolean
}

export function UsageSummary(props: UsageSummaryProps) {
  const { t, i18n } = useTranslation()
  const locale = toIntlLocale(i18n.resolvedLanguage || i18n.language)
  const summary = props.summary
  const cacheRatio = summary?.cache_ratio
  const cacheDescription = t(
    'Cache reads recorded in logs divided by normalized input tokens. Missing upstream cache data does not mean a cache miss.'
  )
  const unknownDisplay = t('Not reported')
  const items = [
    {
      key: 'input',
      title: t('Input tokens'),
      icon: ArrowDownToLine,
      value: formatCompactNumber(summary?.input_tokens ?? 0, locale),
      description: t('Includes recorded cache reads and writes'),
      sparkline: props.series?.map((point) => point.input_tokens),
      tone: 'accent-1' as const,
    },
    {
      key: 'output',
      title: t('Output tokens'),
      icon: ArrowUpFromLine,
      value: formatCompactNumber(summary?.output_tokens ?? 0, locale),
      description: t('Tokens generated by your models'),
      sparkline: props.series?.map((point) => point.output_tokens),
      tone: 'accent-2' as const,
    },
    {
      key: 'read',
      title: t('Recorded cache read'),
      icon: Database,
      value:
        summary?.cache_read_tokens == null
          ? unknownDisplay
          : formatCompactNumber(summary.cache_read_tokens, locale),
      description: t('Part of input; not added to total tokens'),
      tone: 'accent-3' as const,
    },
    {
      key: 'write',
      title: t('Recorded cache write'),
      icon: Layers,
      value:
        summary?.cache_write_tokens == null
          ? unknownDisplay
          : formatCompactNumber(summary.cache_write_tokens, locale),
      description: t('Read and write cache counts may overlap'),
      tone: 'accent-3' as const,
    },
    {
      key: 'ratio',
      title: t('Recorded cache share'),
      icon: Percent,
      value:
        cacheRatio == null
          ? unknownDisplay
          : `${formatNumber(cacheRatio * 100, locale)}%`,
      description: t('Recorded cache reads / input tokens'),
      tone: 'accent-3' as const,
    },
  ].filter((item) => !props.compact || !['read', 'write'].includes(item.key))

  return (
    <div
      className={cn(
        'grid gap-3',
        props.compact
          ? 'grid-cols-1 sm:grid-cols-3'
          : 'grid-cols-2 xl:grid-cols-5'
      )}
    >
      {items.map((item) => (
        <section
          key={item.key}
          aria-label={item.title}
          className='bg-card min-w-0 rounded-xl border p-4 shadow-xs'
        >
          <StatCard
            title={item.title}
            value={item.value}
            description={item.description}
            icon={item.icon}
            tone={item.tone}
            sparkline={item.sparkline}
            sparklineVariant='line'
            showDetailsOnMobile={props.compact && item.key === 'ratio'}
            loading={props.loading}
            action={
              item.key === 'ratio' ? (
                <Tooltip>
                  <TooltipTrigger
                    render={
                      <Button
                        variant='ghost'
                        size='icon'
                        aria-label={t('About recorded cache share')}
                        className='size-6'
                      />
                    }
                  >
                    <Info />
                  </TooltipTrigger>
                  <TooltipContent className='max-w-xs'>
                    {cacheDescription}
                  </TooltipContent>
                </Tooltip>
              ) : undefined
            }
            details={
              props.compact && item.key === 'ratio'
                ? [
                    {
                      label: t('Recorded cache read'),
                      value:
                        summary?.cache_read_tokens == null
                          ? unknownDisplay
                          : formatCompactNumber(
                              summary.cache_read_tokens,
                              locale
                            ),
                    },
                    {
                      label: t('Recorded cache write'),
                      value:
                        summary?.cache_write_tokens == null
                          ? unknownDisplay
                          : formatCompactNumber(
                              summary.cache_write_tokens,
                              locale
                            ),
                    },
                  ]
                : undefined
            }
          />
        </section>
      ))}
    </div>
  )
}
